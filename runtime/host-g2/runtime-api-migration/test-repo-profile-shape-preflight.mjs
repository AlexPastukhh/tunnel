import assert from 'node:assert/strict';
import {classifyProfile,summarizeText} from './repo-profile-shape-preflight.mjs';
const marker='SYNTHETIC_PRIVATE_VALUE_784d';
const normal={config_version:1,control_plane:{tunnel_id:'tunnel_6ac9e4dc9e688191ae1838e858424e8d',api_key:'file:'+marker},mcp:{commands:[{command:'docker exec -i fortis-repo-test node /workspace/repo/.fortis/mcp-bridge.mjs'}]}};
const good=classifyProfile(normal);
assert.equal(good.NoShapeIssuesFound,true);
assert.equal(good.CredentialRepresentation,'FILE_REFERENCE');
assert.equal(JSON.stringify(good).includes(marker),false);
const conflict=classifyProfile({...normal,admin_ui:{open_browser:true},harpoon:{capture_payloads:true}});
assert.deepEqual(conflict.FullOnlyConflicts,['ADMIN_OPEN_BROWSER','HARPOON_CAPTURE_PAYLOADS']);
const extended=classifyProfile({...normal,control_plane:{...normal.control_plane,base_url:'https://'+marker+'.invalid',api_key:marker},mcp:{server_urls:[{url:'https://'+marker+'.invalid'}]},harpoon:{targets:[{label:marker}]}},{OTEL_RESOURCE_ATTRIBUTES:'secret='+marker});
assert.equal(extended.NoShapeIssuesFound,false);
assert.equal(JSON.stringify(extended).includes(marker),false);
assert.equal(extended.ProfileMcpHttpBindingCount,1);
assert.equal(extended.HarpoonTargetCount,1);
const malformed=summarizeText(marker,{JSON_SCHEMA:{},load(){throw Error(marker);}});
assert.equal(malformed.Complete,false);
assert.equal(JSON.stringify(malformed).includes(marker),false);
assert.equal(classifyProfile(null).Complete,false);
assert.equal(classifyProfile({...normal,mcp:{server_urls:marker}}).NoShapeIssuesFound,false);
console.log(JSON.stringify({Check:'REPO_PROFILE_PREFLIGHT_PRIVACY_AND_SHAPE',Passed:true,Cases:6,OwnerDataUsed:false}));
